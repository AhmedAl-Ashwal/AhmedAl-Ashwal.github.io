export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] ?? STRINGS.en;
  const raw = table[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

// Arabic number agreement: 1 and 2 have their own forms, 3–10 take the plural, 11+ the singular accusative.
export function count(lang, base, n) {
  const r = n % 100;
  const form = n === 1 ? 'one' : n === 2 ? 'two' : r >= 3 && r <= 10 ? 'few' : 'many';
  return t(lang, `${base}.${form}`, { n });
}
